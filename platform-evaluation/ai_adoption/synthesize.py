    def ms_mult(p):
        return max(0.2, 1 + te["manager_support_mult"] * p["ms"])

    # ---------------- tiered program participation ----------------
    reg_eff = A["register_role_effect"]
    for p in persons:
        lp = A["register_intercept"] + 1.0 * p["z"] + reg_eff[p["role"]] + A["register_leader_effect"] * p["leader"] + 0.35 * p["ms"]
