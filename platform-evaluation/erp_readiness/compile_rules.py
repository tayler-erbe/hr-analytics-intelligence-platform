"""Compile the rule catalog into one runnable SQL script per warehouse dialect.

    python erp_readiness/compile_rules.py            # writes rules/compiled/{duckdb,snowflake,databricks,oracle}.sql

Rules are authored once in a portable ANSI subset (see catalog.yaml header). This script
renders the date parameters, the recursive-CTE keyword and the staging views for each dialect.
If `sqlglot` is installed (optional) the rule bodies are also transpiled with it, which handles
type spellings (VARCHAR2 on Oracle) and acts as a parse check. The compiled files have NOT been
executed on Snowflake, Databricks or Oracle from this repository - that needs an approved account.
"""
from __future__ import annotations

import re

from common import DIALECTS, RULES_DIR, SOURCE_MAP_PATH, load_catalog, load_yaml, render_sql, staging_sql

try:
    import sqlglot
except ImportError:          # optional
    sqlglot = None

NOTES = {
    "duckdb": "Reference engine; executed by run_checks.py in this repository.",
    "snowflake": "Not executed here. Supports WITH RECURSIVE, LEAD, DATEADD. Run under a role with SELECT on the EDW share/replica.",
    "databricks": "Not executed here. O03 needs recursive CTE support (recent Databricks SQL / DBR) - verify, or swap for a fixed-depth self-join. VARCHAR(n) casts rewritten to STRING.",
    "oracle": "Not executed here. Run ALTER SESSION SET NLS_DATE_FORMAT='YYYY-MM-DD' first so date-to-text casts produce ISO entity IDs. Recursive CTE uses plain WITH plus column list.",
}


def compile_rule(sql: str, dialect: str) -> str:
    rendered = render_sql(sql, dialect)
    if dialect == "duckdb" or sqlglot is None:
        out = rendered
    else:
        out = sqlglot.transpile(rendered, read=None, write=dialect, pretty=True)[0]
    if dialect == "databricks":
        out = re.sub(r"VARCHAR\(\d+\)", "STRING", out)
    return out.strip().rstrip(";")


def compile_all() -> dict[str, str]:
    catalog = load_catalog()
    smap = load_yaml(SOURCE_MAP_PATH)
    outputs = {}
    for d in DIALECTS:
        parts = [f"-- HR conversion-readiness rules v{catalog['version']} compiled for {d}",
                 f"-- {NOTES[d]}",
                 f"-- transpiler: {'sqlglot ' + sqlglot.__version__ if (sqlglot and d != 'duckdb') else 'none (hand-authored portable SQL, tokens rendered)'}",
                 "-- Generated by compile_rules.py from rules/catalog.yaml and rules/source_map.yaml. Do not edit.", ""]
        parts.append("-- 1. Staging views (logical names -> physical EDW tables)")
        for _, s in staging_sql(smap, d):
            parts.append(s + ";")
        parts.append("\n-- 2. Helper views")
        for name, s in catalog["helpers"].items():
            parts.append(f"CREATE OR REPLACE VIEW {name} AS\n{compile_rule(s, d)};")
        parts.append("\n-- 3. Rules (each returns entity_type, entity_id, detail)")
        for r in catalog["rules"]:
            parts.append(f"\n-- {r['id']} [{r['severity']}] {r['name']}\n{compile_rule(r['sql'], d)};")
        outputs[d] = "\n".join(parts) + "\n"
    return outputs


def main():
    out_dir = RULES_DIR / "compiled"
    out_dir.mkdir(exist_ok=True)
    for d, text in compile_all().items():
        (out_dir / f"{d}.sql").write_text(text, encoding="utf-8")
        print(f"wrote rules/compiled/{d}.sql ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
